/** Builds supabase/seed.sql from the catalogue, delivery options and the opening stock. */
import { PRODUCTS } from "../../src/lib/commerce/sample-data";
import { DELIVERY } from "../../src/lib/delivery";
import { SEED_LEVELS } from "../../src/lib/inventory/seed";
import { skuOf } from "../../src/lib/inventory/types";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function seedSql() {
  const products = PRODUCTS.map((p) => `  (${q(p.slug)}, ${q(p.title)}, ${p.price.amount}, ${q(p.price.currencyCode)})`);
  const variants = PRODUCTS.flatMap((p) =>
    p.colorways.flatMap((c) =>
      p.sizes.map((s) => `  (${q(skuOf(p.slug, c.id, s))}, ${q(p.slug)}, ${q(c.id)}, ${q(c.name)}, ${q(s)}, ${SEED_LEVELS[skuOf(p.slug, c.id, s)] ?? 0})`),
    ),
  );
  const delivery = DELIVERY.map((d) => `  (${q(d.id)}, ${q(d.label)}, ${d.fee})`);
  return `-- GENERATED by \`npm run supabase:seed\` from the catalogue. Do not edit by hand.
-- Run after schema.sql. Products, prices and delivery fees are updated to match the
-- catalogue; existing stock counts are never overwritten (new variants get opening stock).

insert into public.products (slug, title, price, currency) values
${products.join(",\n")}
on conflict (slug) do update set title = excluded.title, price = excluded.price, currency = excluded.currency;

insert into public.delivery_options (id, label, fee) values
${delivery.join(",\n")}
on conflict (id) do update set label = excluded.label, fee = excluded.fee;

insert into public.inventory (sku, product_slug, colorway_id, colour_name, size, on_hand) values
${variants.join(",\n")}
on conflict (sku) do update set colour_name = excluded.colour_name;
`;
}
